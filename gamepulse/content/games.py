def resolve_game_id(value) -> str | None:
    """CSV 등에서 들어온 게임 이름/별칭을 내부 game_id 로 변환."""
    if value is None:
        return None
    key = str(value).strip().lower().replace("_", " ")
    for gid, g in GAMES.items():
        if key == gid or key in [a.lower() for a in g["aliases"]] or key == g["name"].lower():
            return gid
    return None
